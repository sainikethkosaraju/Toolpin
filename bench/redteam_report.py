"""Render docs/redteam.md from the committed measurement files (no numbers are typed by hand)."""
import json
from pathlib import Path

D = Path(__file__).resolve().parents[1] / "docs"
b, r1, r2first, fin = (json.loads((D / f).read_text()) for f in
                       ("redteam-baseline.json", "redteam-round1.json", "redteam-round2-first-run.json", "redteam-final.json"))
C = ["scan", "url", "path", "args", "shadow"]
pct = lambda e, m: f"{e}/{m} = {100 * e / m:.1f}%" if m else "n/a"  # noqa: E731
L = ["# Red-team report (generated by `bench/redteam_report.py` from the JSON files in this folder)", "",
     "Method, in order, with the commit or file that proves each step:", "",
     "1. **Baseline** (`redteam-baseline.json`, measured at commit `e116afb` BEFORE any control was changed; the held-out set was frozen "
     "by `corpus/test/FROZEN.sha256` in the same commit).",
     "2. **Round 1** hardening (Unicode/encoding normalisation pipeline, URL/path/injection canonicalisation, multilingual lexicon): `redteam-round1.json`.",
     "3. **Round 2**: a second set of mutation operators written *after* round 1 and never consulted while hardening. "
     "First run: `redteam-round2-first-run.json`. This is the honest overfitting measurement.",
     "4. Round-2 fixes, then `redteam-final.json`. From here round-2 operators are **seen** and no longer count as unseen.", "",
     "Evasion rate = of seed attacks the control blocks in plain form, the fraction a mutation gets past (lower is better).", "",
     "## Mutation-fuzzer evasion", "",
     "| control | baseline | after round 1 (known operators) | **round 2, first run (UNSEEN operators)** | final: known ops | final: round-2 ops (now seen) |",
     "| --- | --- | --- | --- | --- | --- |"]
for c in C:
    L.append(f"| {c} | {pct(b[c]['evaded'], b[c]['mutants'])} | {pct(r1[c]['evaded'], r1[c]['mutants'])} | "
             f"**{pct(r2first['round2_unseen_operators'][c]['evaded'], r2first['round2_unseen_operators'][c]['mutants'])}** | "
             f"{pct(fin[c]['evaded'], fin[c]['mutants'])} | "
             f"{pct(fin['round2_unseen_operators'][c]['evaded'], fin['round2_unseen_operators'][c]['mutants'])} |")
L += ["", "Reading it: round 1 drove the *known* operators to about zero, but against operators it had never seen the evasion rate was "
      "7-71% depending on the control. Round 1's near-zero was largely overfitting to its own test set; the unseen column is the number to trust. "
      "Some residual round-2 'evasions' are not attacks (for example `.//etc/passwd` is a plain relative path, and U+2044 is not a path separator), "
      "so the final round-2 column slightly overstates what is left.", "",
      "## Held-out corpus (108 cases, written before hardening)", "",
      "| control | baseline recall | final recall | baseline precision | final precision | FP (final) |", "| --- | --- | --- | --- | --- | --- |"]
for c in sorted(b["heldout"]):
    x, y = b["heldout"][c], fin["heldout"][c]
    L.append(f"| {c} | {x['recall']:.2f} | {y['recall']:.2f} | {x['precision']:.2f} | {y['precision']:.2f} | {y['FP']} |")
L += ["", "## Why these numbers are not as good as they look", "",
      "- The held-out set, the fuzzer and the controls were all written by the same author. I looked at which held-out cases failed (ids and categories) "
      "before hardening, so the held-out set is *held out from tuning by procedure, not by information*. Independent red-teaming would be better evidence.",
      "- Mutation operators measure resistance to known transformations, not to a creative adversary. Pure paraphrase and novel languages remain undetectable "
      "by pattern matching; that is why the lockfile, policy, IFC and approvals do the real work and the scanner only raises attacker cost.",
      "- Normalisation costs precision: the scanner has false positives on benign text mentioning `.env`, API keys or passwords (see `corpus/RESULTS.md`).",
      "- Remaining known misses: DNS-rebinding hostnames (needs a resolver and pinning), semantic paraphrase, and typosquats that are not token-equivalent.", ""]
(D / "redteam.md").write_text("\n".join(L))
print("\n".join(L[:22]))
